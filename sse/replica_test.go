// TestReplica_ResumeAcross checks that a client resumes on another broker fed
// with the same events and identifiers (FR-037).
func TestReplica_ResumeAcross(t *testing.T) {
	e2e(t, func(e *env) {
		t := e.T
		a, b := newBroker(t), newBroker(t)
		other := newEnv(t, e.H2)
		serveBroker(e, a)
		serveBroker(other, b)
		feed := func(from, to int) {
			for _, id := range busIDs(from, to) {
				mustPublish(t, a, sse.Event{ID: id}, "t")
				mustPublish(t, b, sse.Event{ID: id}, "t")
			}
		}
		c := connect(e, "t", nil)
		feed(1, 10)
		receive(t, c.events, 10)
		c.disconnect()
		feed(11, 20)

		events, _ := subscribe(other, t.Context(), "t", lastEventID("bus-10"))
		if got := ids(receive(t, events, 10)); !slices.Equal(got, busIDs(11, 20)) {
			t.Fatalf("resumed on the other broker with %v", got)
		}
		assertNone(t, events)
	})
}

// TestReplica_GeneratedIDs checks that an identifier generated by one broker is
// never matched to a position in another's history.
func TestReplica_GeneratedIDs(t *testing.T) {
	e2e(t, func(e *env) {
		t := e.T
		a, b := newBroker(t), newBroker(t)
		other := newEnv(t, e.H2)
		serveBroker(e, a)
		serveBroker(other, b)
		events, _ := subscribe(e, t.Context(), "t", nil)
		mustPublish(t, a, sse.Event{Data: "generated"}, "t")
		generated := receive(t, events, 1)[0].ID
		publishIDs(t, b, "t", "x1", "x2", "x3")

		lines := readLines(t, other.Get(t, t.Context(), "/?topics=t", lastEventID(generated)).Body)
		if got := firstBlock(t, lines); !slices.Equal(got, []string{"id: x3"}) {
			t.Fatalf("first block %q, want the position", got)
		}
	})
}

func TestReplica_AnyPoint(t *testing.T) {
	for seed := range uint64(10) {
		t.Run(fmt.Sprint("seed", seed), func(t *testing.T) {
			e2e(t, func(e *env) {
				t := e.T
				opts := []sse.Option{sse.WithHistory(10_001), sse.WithBuffer(10_001)}
				a, b := newBroker(t, opts...), newBroker(t, opts...)
				other := newEnv(t, e.H2)
				serveBroker(e, a)
				serveBroker(other, b)
				anyPoint(t, seed,
					func(ev sse.Event, topic string) {
						mustPublish(t, a, ev, topic)
						mustPublish(t, b, ev, topic)
					},
					func() connection { return connect(e, "a,b", nil) },
					func(lastID string) <-chan sse.Event {
						events, _ := subscribe(other, t.Context(), "a,b", lastEventID(lastID))
						return events
					})
			})
		})
	}
}
