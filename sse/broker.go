package sse

import (
	"errors"
	"fmt"
	"sync"
)

var (
	// ErrClosed is returned by Serve and Publish once the broker is closed.
	ErrClosed = errors.New("sse: broker closed")
	// ErrDuplicateID is returned by Publish for an event whose identifier is
	// still in the history. A feed from an at-least-once message bus can
	// ignore it.
	ErrDuplicateID = errors.New("sse: duplicate event identifier")

	errNoTopic    = errors.New("sse: at least one topic is required")
	errEmptyTopic = errors.New("sse: topics must not be empty")
)

// Broker delivers published events to the requests subscribed to their topics,
// keeps a history to resume clients that reconnect, and can be closed on
// shutdown. It is safe for concurrent use and starts no goroutine: each
// subscription runs in the goroutine of its request.
//
// A broker is per process. With several replicas, feed every replica's broker
// from a shared message bus, using the bus message identifiers as event
// identifiers, so that a client can resume on any replica.
type Broker struct {
	cfg    config
	prefix string

	mu     sync.Mutex
	seq    uint64
	hist   *history
	topics map[string]map[*subscriber]struct{}
	closed bool
	done   chan struct{}
}

// NewBroker returns a broker.
//
// Accepted options: WithRetry, WithWriteTimeout, WithKeepAlive, WithHistory,
// WithBuffer, WithResetEvent and WithReplay.
func NewBroker(opts ...Option) (*Broker, error) {
	cfg, err := newConfig("NewBroker", brokerOptions, opts)
	if err != nil {
		return nil, err
	}
	return &Broker{
		cfg:    cfg,
		prefix: newPrefix(),
		hist:   newHistory(cfg.history),
		topics: make(map[string]map[*subscriber]struct{}),
		done:   make(chan struct{}),
	}, nil
}

// Publish records ev in the history and offers it to the subscribers of any of
// topics, once each, in the order of the history. It never waits for
// subscribers: one whose queue is full is disconnected and resumes from the
// history when it reconnects.
//
// An empty ev.ID is replaced by an identifier generated by the broker. Publish
// returns an error wrapping ErrInvalidEvent for an invalid event,
// ErrDuplicateID when ev.ID is still in the history, ErrClosed after Close, and
// an error when topics is empty or contains an empty topic. In every case
// nothing is recorded or delivered.
func (b *Broker) Publish(ev Event, topics ...string) error {
	if err := ev.validate(); err != nil {
		return err
	}
	ts, err := normalizeTopics(topics)
	if err != nil {
		return err
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return ErrClosed
	}
	if ev.ID != "" && b.hist.contains(ev.ID) {
		return fmt.Errorf("%w: %q", ErrDuplicateID, ev.ID)
	}
	b.seq++
	if ev.ID == "" {
		ev.ID = formatID(b.prefix, b.seq)
	}
	e := entry{seq: b.seq, ev: ev, topics: ts}
	b.hist.add(e)
	for _, t := range ts {
		for sub := range b.topics[t] {
			if sub.lastSeq == e.seq {
				continue // already offered through another topic
			}
			sub.lastSeq = e.seq
			select {
			case sub.queue <- e:
			default:
				b.overflowLocked(sub)
			}
		}
	}
	return nil
}

// Close ends every stream by completing its response normally, so that clients
// reconnect, elsewhere during a deploy, and resume. Serve then returns
// ErrClosed, and later calls to Serve and Publish report ErrClosed. Close does
// not wait for the streams to end, and closing again does nothing.
//
// Register it as the server's shutdown hook, otherwise http.Server.Shutdown
// waits for open streams until its deadline:
//
//	srv.RegisterOnShutdown(broker.Close)
func (b *Broker) Close() {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return
	}
	b.closed = true
	close(b.done)
}

// normalizeTopics checks topics and removes duplicates, keeping their order.
func normalizeTopics(topics []string) ([]string, error) {
	if len(topics) == 0 {
		return nil, errNoTopic
	}
	out := make([]string, 0, len(topics))
	for _, t := range topics {
		if t == "" {
			return nil, errEmptyTopic
		}
		if !containsString(out, t) {
			out = append(out, t)
		}
	}
	return out, nil
}

func containsString(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}

// addLocked registers sub in the topic index.
func (b *Broker) addLocked(sub *subscriber) {
	for _, t := range sub.topics {
		set := b.topics[t]
		if set == nil {
			set = make(map[*subscriber]struct{})
			b.topics[t] = set
		}
		set[sub] = struct{}{}
	}
	sub.lastSeq = b.seq
}

// removeLocked removes sub from the topic index, once.
func (b *Broker) removeLocked(sub *subscriber) {
	if sub.removed {
		return
	}
	sub.removed = true
	for _, t := range sub.topics {
		delete(b.topics[t], sub)
		if len(b.topics[t]) == 0 {
			delete(b.topics, t)
		}
	}
}

// overflowLocked disconnects a subscriber whose queue is full.
func (b *Broker) overflowLocked(sub *subscriber) {
	b.removeLocked(sub)
	sub.overflowed = true
	close(sub.overflow)
}
